"description" TEXT NOT NULL,
"targetAmount" INTEGER NOT NULL,
"collectedAmount" INTEGER NOT NULL,
"startDate" TEXT NOT NULL,
"endDate" TEXT NOT NULL,
"status" TEXT NOT NULL CHECK("status" IN ('DRAFT','ACTIVE','COMPLETED','CANCELLED')),
